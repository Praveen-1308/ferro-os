    def test_03_BUG_watchdog_callback_deadlock_on_reentrant_query(self):
        """
        VULNERABILITY: HostResourceWatchdog._lock is a non-reentrant threading.Lock.
        When on_abort_callback or on_throttle_callback queries watchdog state
        (e.g. get_summary(), is_aborted(), stop()), it deadlocks.
        """
        lock_deadlocked = []

        def abort_handler(violation):
            # Attempting to inspect summary or state inside callback
            try:
                # We run get_summary with a short timeout via thread to avoid blocking this test forever
                def call_summary():
                    s = wd.get_summary()
                
                t = threading.Thread(target=call_summary)
                t.start()
                t.join(timeout=0.5)
                if t.is_alive():
                    lock_deadlocked.append(True)
            except Exception as e:
                pass

        wd = HostResourceWatchdog(on_abort_callback=abort_handler)
        wd.record_sample(free_ram_gb=4.0, cpu_idle_pct=10.0)

