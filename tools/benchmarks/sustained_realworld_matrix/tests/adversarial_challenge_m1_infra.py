    def test_01_pipefail_catches_deep_pipeline_failures(self):
        """Verifies pipefail catches intermediate and multi-stage failures."""
        # Middle failure in 3-stage pipe
        code1, out1, err1 = run_strict_pipe("echo 'alpha beta' | grep 'missing_pattern' | wc -w")
        self.assertEqual(code1, 1, "Middle failure in 3-stage pipe must return exit code 1")

        # First stage failure in 2-stage pipe (cat exits 0)
        code2, out2, err2 = run_strict_pipe("(exit 42) | cat")
        self.assertEqual(code2, 42, "First stage custom exit code must be preserved when downstream exits 0")

        # Rightmost non-zero exit code priority in pipefail
        code3, out3, err3 = run_strict_pipe("(exit 10) | (exit 20) | cat")
        self.assertEqual(code3, 20, "Rightmost failure must take precedence under pipefail")

        # First stage exit code overwritten by downstream failure
        code4, out4, err4 = run_strict_pipe("(exit 42) | grep 'pattern' | wc -l")
        self.assertEqual(code4, 1, "Downstream grep failure (1) takes precedence over upstream 42 in pipefail")

    def test_02_signal_normalization(self):
        """Verifies proper mapping of fatal signals."""
        res_kill = run_strict_command(["bash", "-c", "kill -9 $$"])
        self.assertEqual(res_kill.normalized_exit_code, 137)
        self.assertEqual(res_kill.signal_name, "SIGKILL")

        res_segv = run_strict_command(["bash", "-c", "kill -11 $$"])
        self.assertEqual(res_segv.normalized_exit_code, 139)
        self.assertEqual(res_segv.signal_name, "SIGSEGV")

        res_int = run_strict_command(["bash", "-c", "kill -2 $$"])
        self.assertEqual(res_int.normalized_exit_code, 130)
        self.assertEqual(res_int.signal_name, "SIGINT")

